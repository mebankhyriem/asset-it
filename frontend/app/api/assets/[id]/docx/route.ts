import { NextRequest, NextResponse } from "next/server";
import { verifySession } from "@/lib/dal";
import { getDb } from "@/lib/db/client";
import { CATEGORY_LABELS, CATEGORY_LIFESPAN_YEARS } from "@/lib/types";
import type { IctCategory } from "@/lib/types";
import {
  Document,
  Packer,
  Paragraph,
  Table,
  TableRow,
  TableCell,
  TextRun,
  HeadingLevel,
  AlignmentType,
  WidthType,
  BorderStyle,
  ShadingType,
  Header,
  Footer,
  PageNumber,
  NumberFormat,
} from "docx";

function cell(text: string, bold = false, shaded = false) {
  return new TableCell({
    shading: shaded ? { type: ShadingType.CLEAR, fill: "F3F4F6" } : undefined,
    borders: {
      top:    { style: BorderStyle.SINGLE, size: 1, color: "E5E7EB" },
      bottom: { style: BorderStyle.SINGLE, size: 1, color: "E5E7EB" },
      left:   { style: BorderStyle.SINGLE, size: 1, color: "E5E7EB" },
      right:  { style: BorderStyle.SINGLE, size: 1, color: "E5E7EB" },
    },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [
      new Paragraph({
        children: [new TextRun({ text, bold, size: 22, font: "Calibri" })],
      }),
    ],
  });
}

function row(label: string, value: string) {
  return new TableRow({
    children: [cell(label, true, true), cell(value || "—")],
  });
}

function fmt(dateStr: string | null | undefined) {
  if (!dateStr) return "—";
  return new Date(dateStr).toLocaleDateString("en-IN", {
    day: "2-digit", month: "long", year: "numeric",
  });
}

export async function GET(req: NextRequest, props: { params: Promise<{ id: string }> }) {
  await verifySession();
  const { id } = await props.params;
  const db = getDb();

  const asset = await db.prepare(`
    SELECT a.*, d.name as department_name, u.name as created_by_name
    FROM assets a
    LEFT JOIN departments d ON a.department_id = d.id
    LEFT JOIN users u ON a.created_by = u.id
    WHERE a.id = ?
  `).get(parseInt(id)) as any;

  if (!asset) return NextResponse.json({ error: "Not found" }, { status: 404 });

  // actor_name/actor_role are denormalized directly onto asset_history at write time
  // (see lib/history.ts::recordAssetEvent) — no join needed.
  const history = await db.prepare(`
    SELECT * FROM asset_history WHERE asset_id = ? ORDER BY created_at ASC
  `).all(parseInt(id)) as any[];

  const catLabel = asset.ict_category
    ? CATEGORY_LABELS[asset.ict_category as IctCategory]
    : null;
  const lifespan = asset.ict_category
    ? `${CATEGORY_LIFESPAN_YEARS[asset.ict_category as IctCategory]} years`
    : "—";

  const detailRows = [
    row("Asset ID",             asset.asset_id),
    row("Asset Type",           asset.asset_type),
    row("Serial Number",        asset.serial_number || "—"),
    row("MAC Address",          asset.mac_address || "—"),
    row("Status",               asset.status),
    row("Department",           asset.department_name || "—"),
    row("ICT Category",         asset.ict_category ? `Category ${asset.ict_category}` : "—"),
    row("Policy Classification",catLabel || "—"),
    row("Expected Lifespan",    lifespan),
    row("Issue Date",           fmt(asset.issued_date)),
    row("End of Life Date",     fmt(asset.end_of_life_date)),
    row("Added By",             asset.created_by_name || "—"),
    row("Date Added",           fmt(asset.created_at)),
    row("Last Updated",         fmt(asset.updated_at)),
    row("Specifications",       asset.specifications || "—"),
    row("Description",          asset.description || "—"),
  ];

  if (asset.disposal_method) {
    detailRows.push(
      row("Disposal Method",    asset.disposal_method),
      row("Recycler",           asset.disposal_recycler || "—"),
      row("Reference / Tender", asset.disposal_reference || "—"),
      row("Disposal Date",      fmt(asset.disposal_date)),
    );
  }

  const historyRows = history.map((h) =>
    new TableRow({
      children: [
        cell(fmt(h.created_at)),
        cell(h.event || "—"),
        cell(h.actor_name || "—"),
        cell(h.notes || "—"),
      ],
    })
  );

  const doc = new Document({
    creator: "IT-Asset · NIT Meghalaya",
    title: `Asset Record — ${asset.asset_id}`,
    description: `Asset record for ${asset.asset_id} generated by IT-Asset`,
    sections: [
      {
        headers: {
          default: new Header({
            children: [
              new Paragraph({
                alignment: AlignmentType.RIGHT,
                children: [
                  new TextRun({
                    text: "NIT Meghalaya — IT Asset Management System",
                    size: 18,
                    color: "6B7280",
                    font: "Calibri",
                  }),
                ],
              }),
            ],
          }),
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({ text: "Page ", size: 18, color: "9CA3AF", font: "Calibri" }),
                  new TextRun({ children: [PageNumber.CURRENT], size: 18, color: "9CA3AF", font: "Calibri" }),
                  new TextRun({ text: " of ", size: 18, color: "9CA3AF", font: "Calibri" }),
                  new TextRun({ children: [PageNumber.TOTAL_PAGES], size: 18, color: "9CA3AF", font: "Calibri" }),
                  new TextRun({ text: `  ·  Generated: ${new Date().toLocaleString("en-IN")}`, size: 18, color: "9CA3AF", font: "Calibri" }),
                ],
              }),
            ],
          }),
        },
        children: [
          new Paragraph({
            heading: HeadingLevel.TITLE,
            alignment: AlignmentType.CENTER,
            spacing: { after: 120 },
            children: [
              new TextRun({
                text: "ASSET RECORD",
                bold: true,
                size: 52,
                font: "Calibri",
                color: "111827",
              }),
            ],
          }),
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 400 },
            children: [
              new TextRun({
                text: asset.asset_id,
                size: 30,
                color: "2563EB",
                font: "Calibri",
                bold: true,
              }),
            ],
          }),

          new Paragraph({
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 200, after: 160 },
            children: [new TextRun({ text: "Asset Details", bold: true, size: 28, font: "Calibri" })],
          }),

          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            columnWidths: [3000, 5500],
            rows: detailRows,
          }),

          ...(history.length > 0
            ? [
                new Paragraph({
                  heading: HeadingLevel.HEADING_2,
                  spacing: { before: 400, after: 160 },
                  children: [new TextRun({ text: "Asset History", bold: true, size: 28, font: "Calibri" })],
                }),
                new Table({
                  width: { size: 100, type: WidthType.PERCENTAGE },
                  rows: [
                    new TableRow({
                      tableHeader: true,
                      children: [
                        cell("Date", true, true),
                        cell("Event", true, true),
                        cell("Performed By", true, true),
                        cell("Notes", true, true),
                      ],
                    }),
                    ...historyRows,
                  ],
                }),
              ]
            : []),
        ],
      },
    ],
  });

  const buffer = await Packer.toBuffer(doc);

  return new NextResponse(buffer as unknown as BodyInit, {
    status: 200,
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "Content-Disposition": `attachment; filename="Asset-${asset.asset_id}.docx"`,
    },
  });
}
